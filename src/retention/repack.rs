    #[rstest]
    #[case::ofs_sha1(ObjectFormat::Sha1, 6, false)]
    #[case::ofs_sha256(ObjectFormat::Sha256, 6, false)]
    #[case::ref_sha1(ObjectFormat::Sha1, 7, false)]
