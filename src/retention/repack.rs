/// Bounds one additive repack. Only loose objects and packed fallbacks retain decoded payloads.
#[derive(Debug, Clone, Copy)]
pub struct RepackLimits {
    /// Bounds object count, decoded input bytes, and both output artifacts.
    pub write: PackWriteLimits,
    /// Selects compression for loose objects; defaults to bounded delta search.
    /// Existing packed deltas are reused independently of this policy.
    pub compression: PackCompression,
}

impl Default for RepackLimits {
    fn default() -> Self {
        Self {
            write: PackWriteLimits::default(),
            compression: PackCompression::Delta(crate::DeltaOptions::DEFAULT),
        }
    }
}

impl RepackLimits {
    /// Returns limits for a repository the caller trusts as Git trusts the user's own.
    ///
    /// Git bounds none of these values. The defaults suit untrusted input; these are large enough
    /// that only available memory bounds the work, while keeping headroom for internal arithmetic.
    pub const fn trusted() -> Self {
        Self {
            write: PackWriteLimits::trusted(),
            compression: PackCompression::Delta(crate::DeltaOptions::DEFAULT),
        }
    }
}

/// A complete indexed pack is visible; existing storage has not been removed.
#[derive(Debug, Clone, Copy)]
pub struct RepackPublished {
    /// Identity, count and artifact sizes of the newly published or reused pair.
    pub written: PackWritten,
}

/// Failure before complete pair publication. An unindexed pack may remain after interruption.
#[derive(Debug, thiserror::Error)]
pub enum RepackError {
    /// A fresh retention scan did not establish complete reachability.
    #[error("retention scan incomplete: {0}")]
    Incomplete(String),
    /// A required object disappeared between planning and reading.
    #[error("required object missing: {0}")]
    Missing(ObjectId),
    /// A required object could not be read.
    #[error("cannot read required object {id}")]
    Read {
        /// Object requested by the plan.
        id: ObjectId,
        /// Storage error.
        #[source]
        source: ObjectReadError,
    },
    /// Object storage changed or could not be opened.
    #[error(transparent)]
    Open(#[from] ObjectReadError),
    /// Input or output exceeded the configured bounds, or artifact writing failed.
    #[error(transparent)]
    Write(#[from] PackWriteError),
    /// The caller cancelled before complete pair publication.
    #[error("repack cancelled")]
    Cancelled,
    /// An existing checksum-named artifact differs from the generated bytes.
    #[error("conflicting existing pack artifact: {0}")]
    Existing(std::path::PathBuf),
    /// Temporary artifact creation, synchronization or publication failed.
    #[error(transparent)]
    Io(#[from] io::Error),
}

impl Repository {
    /// Publishes a pack of objects required by a fresh complete retention scan.
    ///
    /// This additive operation rescans roots and recent objects instead of trusting an older
    /// [`super::RetentionPlan`]. Existing compressed entries and delta programs are copied through
    /// pinned packs when their base is retained. Offset-delta framing is rewritten for relocated
    /// bases; an omitted base forces ordinary encoding. Only loose objects undergo new delta
    /// search. It writes two bounded
    /// temporary files in the primary pack directory, synchronizes each file, then publishes the
    /// pack before its index. The index is the visibility marker. An existing checksum-named file
    /// is reused only when every byte matches. Old packs, loose objects, reflogs and alternates
    /// remain untouched, including protected packs. Readers with pinned generations keep their
    /// handles; new readers discover the indexed pair and existing readers can refresh explicitly.
    ///
    /// The caller must exclude cooperating ref, reflog and object writers when it requires a
    /// stable maintenance observation. Girt has no lock that excludes arbitrary external Git
    /// writers. This operation never deletes data, so a concurrent new root cannot make it prune
    /// that root's object. An external writer that removes or mutates input files can still make
    /// the scan/read fail. Do not use this result as deletion authorization. Destructive
    /// maintenance must rescan under its own execution boundary and account for old pinned
    /// readers before removing files.
    ///
    /// # Errors
    ///
    /// Incomplete scans, missing/corrupt objects, limits, I/O and cancellation fail without
    /// replacing an existing artifact. Failure after pack publication can leave an unindexed pack;
    /// readers ignore it and a retry may reuse it. Cancellation after index publication reports
    /// success. Temporary files are cleaned up on ordinary failure but can survive process death.
    /// File contents are synchronized; directory entries are not, so power-loss durability is not
    /// promised. Publication assumes a trusted local filesystem with no in-place artifact edits.
    pub fn repack_retained(
        &self,
        policy: &RetentionPolicy,
        limits: RepackLimits,
        cancel: &AtomicBool,
    ) -> Result<RepackPublished, RepackError> {
        self.repack_retained_after_plan(policy, limits, cancel, || {})
    }

    // The checkpoint makes the scan/write boundary deterministic in concurrency tests.
    fn repack_retained_after_plan(
        &self,
        policy: &RetentionPolicy,
        limits: RepackLimits,
        cancel: &AtomicBool,
        after_plan: impl FnOnce(),
    ) -> Result<RepackPublished, RepackError> {
        check(cancel)?;
        let objects =
            self.objects_controlled(policy.packs, crate::AlternateLimits::default(), cancel)?;
        let plan = self.plan_retention_from(policy, cancel, Some(&objects));
        if let super::RetentionOutcome::Incomplete(reason) = plan.outcome {
            return Err(RepackError::Incomplete(reason));
        }
        after_plan();
        check(cancel)?;
        let count = u32::try_from(plan.required.len())
            .map_err(|_| PackWriteError::Limit("object count"))?;
        if count > limits.write.max_objects {
            return Err(PackWriteError::Limit("object count").into());
        }
        let mut decoded = Vec::new();
        let mut reused = Vec::new();
        let mut fallback = Vec::new();
        let mut bytes = 0u64;
        for &id in &plan.required {
            check(cancel)?;
            let location = objects.packed_location(id)?;
            if let Some((pack, position)) = &location {
                let entry = ReusedEntry::new(std::sync::Arc::clone(pack), *position)?;
                if entry.base.is_none_or(|base| plan.required.contains(&base)) {
                    let len = pack.result_size(&entry.entry, &entry.header)? as u64;
                    charge_input(len, &mut bytes, limits.write)?;
                    reused.push(entry);
                    continue;
                }
            }
            let object = objects
                .read_controlled(id, policy.read, cancel)
                .map_err(|source| RepackError::Read { id, source })?
                .or_else(|| super::canonical_empty_tree(id))
                .ok_or(RepackError::Missing(id))?;
            charge_input(object.data().len() as u64, &mut bytes, limits.write)?;
            if location.is_some() {
                fallback.push((id, object));
            } else {
                decoded.push((id, object));
            }
        }
        let ordinary = fallback.len();
        fallback.extend(decoded);
        let decoded = fallback;
        let input: Vec<_> = decoded
            .iter()
            .map(|(id, object)| PackObject {
                id: *id,
                kind: object.kind(),
                data: object.data(),
            })
            .collect();
        let directory = self.object_dir().join("pack");
        fs::create_dir_all(&directory)?;
        let mut pack = NamedTempFile::new_in(&directory)?;
        let mut index = NamedTempFile::new_in(&directory)?;
        let write_result = write_reused(
            self.object_format(),
            &mut reused,
            (&input[..ordinary], &input[ordinary..]),
            (
                &mut BufWriter::new(&mut pack),
                &mut BufWriter::new(&mut index),
            ),
            limits.write,
            limits.compression,
            cancel,
        )
        .map_err(|error| match error {
            ReuseError::Read(error) => RepackError::Open(error),
            ReuseError::Write(error) => RepackError::Write(error),
        });
        let written = match write_result {
            Err(_) if cancel.load(Ordering::Relaxed) => return Err(RepackError::Cancelled),
            result => result?,
        };
        pack.as_file().sync_all()?;
        index.as_file().sync_all()?;
        let basename = directory.join(format!("pack-{}", written.checksum));
        publish_pair(pack, index, &basename, cancel, || {})?;
        Ok(RepackPublished { written })
    }
}

fn charge_input(len: u64, bytes: &mut u64, limits: PackWriteLimits) -> Result<(), PackWriteError> {
    if len > limits.max_object_bytes {
        return Err(PackWriteError::Limit("object bytes"));
    }
    *bytes = bytes
        .checked_add(len)
        .ok_or(PackWriteError::Limit("input bytes"))?;
    if *bytes > limits.max_input_bytes {
        return Err(PackWriteError::Limit("input bytes"));
    }
    Ok(())
}

fn publish_pair(
    pack: NamedTempFile,
    index: NamedTempFile,
    basename: &Path,
    cancel: &AtomicBool,
    after_pack: impl FnOnce(),
) -> Result<(), RepackError> {
    check(cancel)?;
    publish(pack, &basename.with_extension("pack"), cancel)?;
    after_pack();
    check(cancel)?;
    publish(index, &basename.with_extension("idx"), cancel)?;
    Ok(())
}

fn check(cancel: &AtomicBool) -> Result<(), RepackError> {
    if cancel.load(Ordering::Relaxed) {
        Err(RepackError::Cancelled)
    } else {
        Ok(())
    }
}

fn publish(temporary: NamedTempFile, path: &Path, cancel: &AtomicBool) -> Result<(), RepackError> {
    match temporary.persist_noclobber(path) {
        Ok(_) => Ok(()),
        Err(error) if error.error.kind() == io::ErrorKind::AlreadyExists => {
            let mut existing = File::open(path)?;
            let mut candidate = error.file.reopen()?;
            if existing.metadata()?.len() != candidate.metadata()?.len() {
                return Err(RepackError::Existing(path.into()));
            }
            let mut a = [0; 8192];
            let mut b = [0; 8192];
            loop {
                check(cancel)?;
                let n = existing.read(&mut a)?;
                candidate.read_exact(&mut b[..n])?;
                if a[..n] != b[..n] {
                    return Err(RepackError::Existing(path.into()));
                }
                if n == 0 {
                    return Ok(());
                }
            }
        }
        Err(error) => Err(error.error.into()),
    }
}

#[cfg(test)]
mod tests {
    use std::io::Write;

    use super::*;

    #[test]
    fn default_repack_searches_only_new_loose_objects() {
        let root = tempfile::tempdir().unwrap();
        let repository = Repository::init(
            crate::ObjectFormat::Sha1,
            root.path().join("repo"),
            crate::InitKind::Bare,
        )
        .unwrap();
        let base: Vec<u8> = (0..=255).cycle().take(4096).collect();
        let mut target = base.clone();
        target[1000] ^= 255;
        repository.loose_objects().write_blob(&base).unwrap();
        repository.loose_objects().write_blob(&target).unwrap();
        let cancel = AtomicBool::new(false);
        let first = repository
            .repack_retained(
                &RetentionPolicy::default(),
                RepackLimits::default(),
                &cancel,
            )
            .unwrap();
        let second = repository
            .repack_retained(
                &RetentionPolicy::default(),
                RepackLimits::default(),
                &cancel,
            )
            .unwrap();
        assert_eq!(first.written.deltas.entries, 1);
        assert!(first.written.deltas.candidates > 0);
        assert_eq!(second.written.deltas.entries, 1);
        assert_eq!(second.written.deltas.candidates, 0);
        assert_eq!(first.written.checksum, second.written.checksum);
    }

    #[test]
    fn cancellation_between_publications_leaves_only_an_unindexed_pack() {
        let root = tempfile::tempdir().unwrap();
        let basename = root.path().join("pack-test");
        let mut pack = NamedTempFile::new_in(root.path()).unwrap();
        let mut index = NamedTempFile::new_in(root.path()).unwrap();
        pack.write_all(b"pack bytes").unwrap();
        index.write_all(b"index bytes").unwrap();
        let cancelled = AtomicBool::new(false);
        let result = publish_pair(pack, index, &basename, &cancelled, || {
            assert!(basename.with_extension("pack").exists());
            assert!(!basename.with_extension("idx").exists());
            cancelled.store(true, Ordering::Relaxed);
        });
        assert!(matches!(result, Err(RepackError::Cancelled)));
        assert_eq!(
            fs::read(basename.with_extension("pack")).unwrap(),
            b"pack bytes"
        );
        assert!(!basename.with_extension("idx").exists());
    }

    #[test]
    fn conflicting_existing_artifact_is_not_overwritten() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("pack-existing.pack");
        fs::write(&path, b"old bytes").unwrap();
        let mut candidate = NamedTempFile::new_in(root.path()).unwrap();
        candidate.write_all(b"new bytes").unwrap();
        let result = publish(candidate, &path, &AtomicBool::new(false));
        assert!(matches!(result, Err(RepackError::Existing(_))));
        assert_eq!(fs::read(path).unwrap(), b"old bytes");
    }

    #[rstest::rstest]
    #[case::sha1_offset(crate::ObjectFormat::Sha1, 6)]
    #[case::sha1_reference(crate::ObjectFormat::Sha1, 7)]
    #[case::sha256_offset(crate::ObjectFormat::Sha256, 6)]
    #[case::sha256_reference(crate::ObjectFormat::Sha256, 7)]
    fn omitted_delta_base_is_reencoded_without_search(
        #[case] format: crate::ObjectFormat,
        #[case] code: u8,
    ) {
        let root = tempfile::tempdir().unwrap();
        let repository =
            Repository::init(format, root.path().join("repo"), crate::InitKind::Bare).unwrap();
        let (_, base, target) =
            crate::pack::reuse::tests::fixture(&repository.object_dir().join("pack"), format, code);
        let policy = RetentionPolicy {
            heads: vec![target],
            recent_cutoff: std::time::SystemTime::now() + std::time::Duration::from_secs(60),
            ..Default::default()
        };
        let published = repository
            .repack_retained(&policy, RepackLimits::default(), &AtomicBool::new(false))
            .unwrap();
        let index = repository
            .object_dir()
            .join(format!("pack/pack-{}.idx", published.written.checksum));
        let pack = crate::pack::FilePack::open(
            format,
            &index,
            &mut crate::PackLimits::default(),
            &AtomicBool::new(false),
        )
        .unwrap();
        assert!(pack.find(base).unwrap().is_none());
        assert_eq!(
            pack.read(
                pack.find(target).unwrap().unwrap(),
                crate::ReadLimits::default(),
                &AtomicBool::new(false)
            )
            .unwrap()
            .data(),
            b"target payload"
        );
        assert_eq!(published.written.deltas.entries, 0);
        assert_eq!(published.written.deltas.candidates, 0);
    }

    #[rstest::rstest]
    #[case::individual(10, 100, "object bytes")]
    #[case::aggregate(100, 10, "input bytes")]
    fn reused_delta_payload_is_charged_before_publication(
        #[case] maximum: u64,
        #[case] total: u64,
        #[case] label: &str,
    ) {
        let root = tempfile::tempdir().unwrap();
        let format = crate::ObjectFormat::Sha1;
        let repository =
            Repository::init(format, root.path().join("repo"), crate::InitKind::Bare).unwrap();
        let (_, base, target) =
            crate::pack::reuse::tests::fixture(&repository.object_dir().join("pack"), format, 6);
        let policy = RetentionPolicy {
            heads: vec![base, target],
            ..Default::default()
        };
        let limits = RepackLimits {
            write: PackWriteLimits {
                max_object_bytes: maximum,
                max_input_bytes: total,
                ..Default::default()
            },
            ..Default::default()
        };
        let result = repository.repack_retained(&policy, limits, &AtomicBool::new(false));
        assert!(
            matches!(result, Err(RepackError::Write(PackWriteError::Limit(actual))) if actual == label)
        );
        assert_eq!(
            fs::read_dir(repository.object_dir().join("pack"))
                .unwrap()
                .count(),
            2
        );
    }

    #[test]
    fn new_loose_object_after_scan_survives_additive_publication() {
        let root = tempfile::tempdir().unwrap();
        let repository = Repository::init(
            crate::ObjectFormat::Sha1,
            root.path().join("repo"),
            crate::InitKind::Bare,
        )
        .unwrap();
        let mut new_id = None;
        repository
            .repack_retained_after_plan(
                &RetentionPolicy::default(),
                RepackLimits::default(),
                &AtomicBool::new(false),
                || {
                    new_id = Some(
                        repository
                            .loose_objects()
                            .write_blob(b"new writer")
                            .unwrap(),
                    )
                },
            )
            .unwrap();
        let id = new_id.unwrap();
        assert_eq!(
            repository.loose_objects().read_blob(id, 64).unwrap(),
            b"new writer"
        );
    }
}
