/// Bounds one additive repack.
///
/// Entries copied from existing packs are never decoded, so they count toward the object count and
/// the output bounds but not the decoded-input bounds. Objects that are decoded, such as loose
/// objects, stay in memory until the pack is written.
#[derive(Debug, Clone, Copy)]
pub struct RepackLimits {
    /// Bounds object count, decoded input bytes, and both output artifacts.
    pub write: PackWriteLimits,
    /// Selects ordinary or bounded delta compression for decoded objects (default: deltas).
    ///
    /// Copied pack entries keep their stored form whatever this value is.
    pub compression: PackCompression,
}

impl Default for RepackLimits {
    fn default() -> Self {
        Self {
            write: PackWriteLimits::default(),
            compression: PackCompression::Delta(DeltaOptions::DEFAULT),
        }
    }
}

impl RepackLimits {
    /// Returns limits for a repository the caller trusts as Git trusts the user's own.
    ///
    /// Git bounds none of these values. The defaults suit untrusted input; these are large enough
    /// that only available memory bounds the work, while keeping headroom for internal arithmetic.
    pub const fn trusted() -> Self {
        Self {
            write: PackWriteLimits::trusted(),
            compression: PackCompression::Delta(DeltaOptions::DEFAULT),
        }
    }
}

/// A complete indexed pack is visible; existing storage has not been removed.
#[derive(Debug, Clone, Copy)]
pub struct RepackPublished {
    /// Identity, count and artifact sizes of the newly published or reused pair.
    pub written: PackWritten,
    /// Entries copied from existing packs without decoding, deltas included.
    pub reused: u32,
}

/// Failure before complete pair publication. An unindexed pack may remain after interruption.
#[derive(Debug, thiserror::Error)]
pub enum RepackError {
    /// A fresh retention scan did not establish complete reachability.
    #[error("retention scan incomplete: {0}")]
    Incomplete(String),
    /// A required object disappeared between planning and reading.
    #[error("required object missing: {0}")]
    Missing(ObjectId),
    /// A required object could not be read.
    #[error("cannot read required object {id}")]
    Read {
        /// Object requested by the plan.
        id: ObjectId,
        /// Storage error.
        #[source]
        source: ObjectReadError,
    },
    /// Object storage changed or could not be opened.
    #[error(transparent)]
    Open(#[from] ObjectReadError),
    /// Input or output exceeded the configured bounds, or artifact writing failed.
    #[error(transparent)]
    Write(#[from] PackWriteError),
    /// The caller cancelled before complete pair publication.
    #[error("repack cancelled")]
    Cancelled,
    /// An existing checksum-named artifact differs from the generated bytes.
    #[error("conflicting existing pack artifact: {0}")]
    Existing(std::path::PathBuf),
    /// Temporary artifact creation, synchronization or publication failed.
    #[error(transparent)]
    Io(#[from] io::Error),
}

impl Repository {
    /// Publishes a pack of objects required by a fresh complete retention scan.
    ///
    /// An object stored in a pack is copied as stored: its compressed bytes are not inflated and
    /// a delta stays a delta, provided its base is also required. An OFS_DELTA stays one when its
    /// base precedes it in the new pack, and otherwise becomes a REF_DELTA. Copied
    /// entries come from pack files whose checksum and per-entry CRCs were verified when opened,
    /// but their object IDs are not recomputed; [`Repository::retire_old_packs`] reads every
    /// required object back from the new pack before it removes anything. A delta whose base is
    /// not required, or that would close a delta cycle across packs, is decoded and written as a
    /// new entry. Objects not in any pack (loose objects, the canonical empty tree) are decoded and
    /// delta-compressed against each other under [`RepackLimits::compression`]; they are not
    /// searched for bases among the copied entries.
    ///
    /// This additive operation rescans roots and recent objects instead of trusting an older
    /// [`super::RetentionPlan`]. It reads required objects through pinned packs, writes two bounded
    /// temporary files in the primary pack directory, synchronizes each file, then publishes the
    /// pack before its index. The index is the visibility marker. An existing checksum-named file
    /// is reused only when every byte matches. Old packs, loose objects, reflogs and alternates
    /// remain untouched, including protected packs. Readers with pinned generations keep their
    /// handles; new readers discover the indexed pair and existing readers can refresh explicitly.
    ///
    /// The caller must exclude cooperating ref, reflog and object writers when it requires a
    /// stable maintenance observation. Girt has no lock that excludes arbitrary external Git
    /// writers. This operation never deletes data, so a concurrent new root cannot make it prune
    /// that root's object. An external writer that removes or mutates input files can still make
    /// the scan/read fail. Do not use this result as deletion authorization. Destructive
    /// maintenance must rescan under its own execution boundary and account for old pinned
    /// readers before removing files.
    ///
    /// # Errors
    ///
    /// Incomplete scans, missing/corrupt objects, limits, I/O and cancellation fail without
    /// replacing an existing artifact. Failure after pack publication can leave an unindexed pack;
    /// readers ignore it and a retry may reuse it. Cancellation after index publication reports
    /// success. Temporary files are cleaned up on ordinary failure but can survive process death.
    /// File contents are synchronized; directory entries are not, so power-loss durability is not
    /// promised. Publication assumes a trusted local filesystem with no in-place artifact edits.
    pub fn repack_retained(
        &self,
        policy: &RetentionPolicy,
        limits: RepackLimits,
        cancel: &AtomicBool,
    ) -> Result<RepackPublished, RepackError> {
        self.repack_retained_after_plan(policy, limits, cancel, || {})
    }

    // The checkpoint makes the scan/write boundary deterministic in concurrency tests.
    fn repack_retained_after_plan(
        &self,
        policy: &RetentionPolicy,
        limits: RepackLimits,
        cancel: &AtomicBool,
        after_plan: impl FnOnce(),
    ) -> Result<RepackPublished, RepackError> {
        check(cancel)?;
        let plan = self.plan_retention(policy, cancel);
        if let super::RetentionOutcome::Incomplete(reason) = plan.outcome {
            return Err(RepackError::Incomplete(reason));
        }
        after_plan();
        self.repack_required(plan.required, policy, limits, cancel)
    }

    /// Publishes `required` without scanning again; the caller owns the plan's freshness.
    pub(super) fn repack_required(
        &self,
        required: BTreeSet<ObjectId>,
        policy: &RetentionPolicy,
        limits: RepackLimits,
        cancel: &AtomicBool,
    ) -> Result<RepackPublished, RepackError> {
        check(cancel)?;
        let objects =
            self.objects_controlled(policy.packs, crate::AlternateLimits::default(), cancel)?;
        let count =
            u32::try_from(required.len()).map_err(|_| PackWriteError::Limit("object count"))?;
        if count > limits.write.max_objects {
            return Err(PackWriteError::Limit("object count").into());
        }
        let packs = objects.packs();
        let (reused, to_decode) = plan_reuse(&packs, &required, cancel)?;
        let mut decoded = Vec::with_capacity(to_decode.len());
        let mut bytes = 0u64;
        for id in to_decode {
            check(cancel)?;
            let object = objects
                .read_controlled(id, policy.read, cancel)
                .map_err(|source| RepackError::Read { id, source })?
                .or_else(|| super::canonical_empty_tree(id))
                .ok_or(RepackError::Missing(id))?;
            let len = object.data().len() as u64;
            if len > limits.write.max_object_bytes {
                return Err(PackWriteError::Limit("object bytes").into());
            }
            bytes = bytes
                .checked_add(len)
                .ok_or(PackWriteError::Limit("input bytes"))?;
            if bytes > limits.write.max_input_bytes {
                return Err(PackWriteError::Limit("input bytes").into());
            }
            decoded.push((id, object));
        }
        let input: Vec<_> = decoded
            .iter()
            .map(|(id, object)| PackObject {
                id: *id,
                kind: object.kind(),
                data: object.data(),
            })
            .collect();
        let directory = self.object_dir().join("pack");
        fs::create_dir_all(&directory)?;
        let mut pack = NamedTempFile::new_in(&directory)?;
        let mut index = NamedTempFile::new_in(&directory)?;
        // A failed copy is reported with the object it concerned, not as an opaque write error.
        let mut copy_failure = None;
        let write_result = write_reusing_observed(
            self.object_format(),
            &reused,
            &mut |entry| {
                packs[entry.source.0]
                    .compressed(entry.source.1)
                    .map_err(|source| {
                        copy_failure = Some((entry.id, source));
                        PackWriteError::Io(io::ErrorKind::InvalidData.into())
                    })
            },
            &input,
            (&mut pack, &mut index),
            limits.write,
            limits.compression,
            &mut || {
                if cancel.load(Ordering::Relaxed) {
                    Err(PackWriteError::Io(io::ErrorKind::Interrupted.into()))
                } else {
                    Ok(())
                }
            },
            &mut |_, _| {},
        );
        let written = match write_result {
            Err(_) if cancel.load(Ordering::Relaxed) => return Err(RepackError::Cancelled),
            Err(_) if copy_failure.is_some() => {
                let (id, source) = copy_failure.take().expect("checked above");
                return Err(RepackError::Read { id, source });
            }
            result => result?,
        };
        pack.as_file().sync_all()?;
        index.as_file().sync_all()?;
        let basename = directory.join(format!("pack-{}", written.checksum));
        publish_pair(pack, index, &basename, cancel, || {})?;
        Ok(RepackPublished {
            written,
            reused: reused.len() as u32,
        })
    }
}

/// Splits the required objects into pack entries to copy verbatim and objects to decode.
///
/// An object found in a pack is copied, including a delta, when its base is also required and
/// copying does not create a delta cycle between packs. Everything else, such as loose objects,
/// is decoded and written as a new entry.
fn plan_reuse(
    packs: &[&FilePack],
    required: &BTreeSet<ObjectId>,
    cancel: &AtomicBool,
) -> Result<(Vec<Reuse>, Vec<ObjectId>), RepackError> {
    let mut located: Vec<(usize, Reuse)> = Vec::new();
    let mut to_decode = Vec::new();
    for &id in required {
        check(cancel)?;
        let mut found = None;
        for (index, pack) in packs.iter().enumerate() {
            let read = |source| RepackError::Read { id, source };
            if let Some(position) = pack.find(id).map_err(read)? {
                found = Some((index, position));
                break;
            }
        }
        let Some((index, position)) = found else {
            to_decode.push(id);
            continue;
        };
        let read = |source| RepackError::Read { id, source };
        let described = packs[index].describe(position).map_err(read)?;
        if described.base.is_some_and(|base| !required.contains(&base)) {
            to_decode.push(id);
            continue;
        }
        let offset = packs[index].entry_offset(position).map_err(read)?;
        located.push((
            offset,
            Reuse {
                id,
                code: described.code,
                size: described.size,
                base: described.base,
                by_offset: described.by_offset,
                source: (index, position),
            },
        ));
    }
    // Packs may have been built independently, so one's delta can name another's as its base,
    // and the reverse. Break any cycle by decoding one member.
    let by_id: HashMap<ObjectId, usize> = located
        .iter()
        .enumerate()
        .map(|(index, (_, entry))| (entry.id, index))
        .collect();
    let mut state = vec![0u8; located.len()];
    let mut demoted = vec![false; located.len()];
    for start in 0..located.len() {
        check(cancel)?;
        let mut path = Vec::new();
        let mut next = Some(start);
        while let Some(index) = next {
            match state[index] {
                2 => break,
                1 => {
                    demoted[index] = true;
                    break;
                }
                _ => {}
            }
            state[index] = 1;
            path.push(index);
            next = located[index]
                .1
                .base
                .and_then(|base| by_id.get(&base).copied());
        }
        for index in path {
            state[index] = 2;
        }
    }
    let mut kept = Vec::with_capacity(located.len());
    for (index, entry) in located.into_iter().enumerate() {
        if demoted[index] {
            to_decode.push(entry.1.id);
        } else {
            kept.push(entry);
        }
    }
    // Source order keeps each pack's bases ahead of their dependents and reads sequential.
    kept.sort_unstable_by_key(|(offset, entry)| (entry.source.0, *offset));
    Ok((
        kept.into_iter().map(|(_, entry)| entry).collect(),
        to_decode,
    ))
}

fn publish_pair(
    pack: NamedTempFile,
    index: NamedTempFile,
    basename: &Path,
    cancel: &AtomicBool,
    after_pack: impl FnOnce(),
) -> Result<(), RepackError> {
    check(cancel)?;
    publish(pack, &basename.with_extension("pack"), cancel)?;
    after_pack();
    check(cancel)?;
    publish(index, &basename.with_extension("idx"), cancel)?;
    Ok(())
}

fn check(cancel: &AtomicBool) -> Result<(), RepackError> {
    if cancel.load(Ordering::Relaxed) {
        Err(RepackError::Cancelled)
    } else {
        Ok(())
    }
}

fn publish(temporary: NamedTempFile, path: &Path, cancel: &AtomicBool) -> Result<(), RepackError> {
    match temporary.persist_noclobber(path) {
        Ok(_) => Ok(()),
        Err(error) if error.error.kind() == io::ErrorKind::AlreadyExists => {
            let mut existing = File::open(path)?;
            let mut candidate = error.file.reopen()?;
            if existing.metadata()?.len() != candidate.metadata()?.len() {
                return Err(RepackError::Existing(path.into()));
            }
            let mut a = [0; 8192];
            let mut b = [0; 8192];
            loop {
                check(cancel)?;
                let n = existing.read(&mut a)?;
                candidate.read_exact(&mut b[..n])?;
                if a[..n] != b[..n] {
                    return Err(RepackError::Existing(path.into()));
                }
                if n == 0 {
                    return Ok(());
                }
            }
        }
        Err(error) => Err(error.error.into()),
    }
}

