        'baselines and verify unchanged jj operation heads. Later mutation inputs were rebuilt',
        'after history rendering accumulated internal Git objects; subsequent read cells use',
        'separate baselines to preserve pristine mutation inputs. Automatic Git maintenance is disabled',
        'in the later run epoch; explicit GC remains measured.', '',
        'Linux has tracked paths differing only by case. On case-insensitive APFS, Git rebase',
        'setup verifies that every unstaged path is such an alias and marks only those paths',
        'assume-unchanged before timing. Other unstaged edits fail setup. This platform limitation',
        'means the checkout cannot represent both versions of those files faithfully.', '',
        'The original method takes six samples per tool in Git, girt, stock, stock, girt, Git',
        'blocks. The remaining Linux cells use adaptive calibration in Git, stock, girt order:',
        'if the slowest first sample exceeds 60 seconds, take one sample per tool; if it exceeds',
        '10 seconds, take three; otherwise take six. Further samples alternate girt and stock',
        'positions. Preserve completed older cells and partial samples on resume. Slow-cell ratios',
        'therefore have lower precision. Counts in the JSON describe the samples actually retained.',
        '',
        'Kill each timed girt process group at `max(2 × first stock-jj seconds, 5 seconds)`.',
